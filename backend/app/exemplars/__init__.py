"""Βιβλιοθήκη υποδειγματικών σχεδίων δικογράφων του γραφείου.

Κάθε υπόδειγμα είναι πλήρες σχέδιο κατά το πρότυπο του γραφείου — με
[ΣΥΜΠΛΗΡΩΣΤΕ] σε κάθε σημείο που εξαρτάται από την εκάστοτε υπόθεση (και
στη νομολογία, η οποία ΔΕΝ αναπληρώνεται με επινοημένους αριθμούς) — και
συνοδεύεται από σημειώσεις συντάξεως που εξηγούν τη νομική, την ουσιαστική
και τη δομική «οικονομία» του: γιατί κάθε τμήμα βρίσκεται εκεί που
βρίσκεται και σε αυτή την αναλογία.

Τα υποδείγματα τροφοδοτούν και το στάδιο 2 του ελέγχου ως πρότυπο αναφοράς
του οικείου είδους.
"""

from dataclasses import dataclass
from pathlib import Path

_DIR = Path(__file__).parent


def _load(filename: str) -> str:
    return (_DIR / filename).read_text(encoding="utf-8").strip()


@dataclass(frozen=True)
class Exemplar:
    doc_type: str  # κλειδί μητρώου ειδών (checklists.DOCUMENT_TYPES)
    title: str
    scenario: str
    body: str
    drafting_notes: list[str]
    key_provisions: list[str]


EXEMPLARS: dict[str, Exemplar] = {}


def _register(exemplar: Exemplar) -> None:
    EXEMPLARS[exemplar.doc_type] = exemplar


