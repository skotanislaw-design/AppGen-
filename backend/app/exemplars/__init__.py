from dataclasses import dataclass
from pathlib import Path

_DIR = Path(__file__).parent


def _load(filename: str) -> str:
    return (_DIR / filename).read_text(encoding="utf-8").strip()


@dataclass(frozen=True)
class Exemplar:
    doc_type: str  # κλειδί μητρώου ειδών (checklists.DOCUMENT_TYPES)
    title: str
    scenario: str
    body: str
    drafting_notes: list[str]
    key_provisions: list[str]


EXEMPLARS: dict[str, Exemplar] = {}


def _register(exemplar: Exemplar) -> None:
    EXEMPLARS[exemplar.doc_type] = exemplar


