"""Εξειδικευμένοι ελεγκτές ανά κλάδο δικαίου.

Η ταξινόμηση του σταδίου 1 δρομολογεί το δικόγραφο στον ειδικό του οικείου
κλάδου: ο έλεγχος ενός ποινικού δικογράφου γίνεται από ποινικολόγο, ενός
διοικητικού από διοικητικολόγο κ.ο.κ. Κάθε προφίλ ορίζει την ταυτότητα, το
γνωστικό υπόβαθρο και το δόγμα ελέγχου του ειδικού — δηλαδή τι κοιτάζει
πρώτα, ποιες είναι οι μοιραίες παγίδες του κλάδου του και με ποια νομολογία
και θεωρία διασταυρώνει τις κρίσεις του.
"""

from dataclasses import dataclass


@dataclass(frozen=True)
class ExpertProfile:
    branch: str
    title: str
    description: str  # σύντομη περιγραφή για το UI/report
    identity: str  # τμήμα system prompt: ταυτότητα + δόγμα ελέγχου του κλάδου


EXPERTS: dict[str, ExpertProfile] = {}


def _register(profile: ExpertProfile) -> None:
    EXPERTS[profile.branch] = profile


