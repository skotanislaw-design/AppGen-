"""Μητρώο κριτηρίων νομικής πληρότητας ανά είδος δικογράφου.

Κάθε είδος εγγράφου αντιστοιχίζεται σε δέσμη κριτηρίων: τα καθολικά κριτήρια
(εφαρμόζονται σε κάθε δικόγραφο) συν τα ειδικά κριτήρια του είδους, με τις
οικείες δικονομικές/ουσιαστικές διατάξεις. Τα κριτήρια αξιολογούνται από το
μοντέλο ένα προς ένα· η βαθμολόγηση γίνεται ντετερμινιστικά στο scorer.
"""

from dataclasses import dataclass, field
from enum import Enum


class Category(str, Enum):
    FORMAL = "formal"
    SUBSTANTIVE = "substantive"
    GROUNDING = "grounding"
    LANGUAGE = "language"


CATEGORY_LABELS: dict[Category, str] = {
    Category.FORMAL: "Τυπική πληρότητα",
    Category.SUBSTANTIVE: "Ουσιαστική πληρότητα",
    Category.GROUNDING: "Νομική τεκμηρίωση",
    Category.LANGUAGE: "Δομή & νομικός λόγος",
}

# Βάρη κατηγοριών στο συνολικό ποσοστό.
CATEGORY_WEIGHTS: dict[Category, float] = {
    Category.FORMAL: 0.25,
    Category.SUBSTANTIVE: 0.35,
    Category.GROUNDING: 0.25,
    Category.LANGUAGE: 0.15,
}


@dataclass(frozen=True)
class Criterion:
    id: str
    category: Category
    text: str
    weight: float = 1.0
    # Κρίσιμο κριτήριο: η πλήρης απουσία του καθιστά το δικόγραφο απαράδεκτο
    # ή δικονομικά μετέωρο και θέτει οροφή στη συνολική βαθμολογία.
    critical: bool = False


@dataclass(frozen=True)
class DocumentTypeSpec:
    key: str
    label: str
    branch: str  # penal | civil | administrative | extrajudicial | generic
    description: str
    criteria: list[Criterion] = field(default_factory=list)


