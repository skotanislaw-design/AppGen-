def get_spec(key: str) -> DocumentTypeSpec:
    """Επιστρέφει το spec του είδους ή το generic fallback."""
    return DOCUMENT_TYPES.get(key, DOCUMENT_TYPES["generic"])


def criteria_for(key: str) -> list[Criterion]:
    """Καθολικά + ειδικά κριτήρια για το δοθέν είδος."""
    return [*UNIVERSAL_CRITERIA, *get_spec(key).criteria]


def classification_menu() -> str:
    """Κείμενο επιλογών ταξινόμησης για το prompt του classifier."""
    lines = [
        f"- {spec.key} ({spec.branch}): {spec.label} — {spec.description}"
        for spec in DOCUMENT_TYPES.values()
    ]
    return "\n".join(lines)
